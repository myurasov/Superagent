"""Generate `superagent/agents/_manifest.yaml`: the roster of agent roles.

Implements contracts/agents.md "Manifest". The manifest is one small file an
agent reads to learn which roles exist, what each is for, which skills and
duties it has and where its dev twin lives, without opening every role file.
It is derived: the role files are the source, and the tools
(`tools/agents.py`, `tools/cadence.py`) read those directly, so a stale
manifest never changes behavior. Re-run after any change to a role file.

  (no flag)   write the manifest
  --check     write nothing; exit 1 when the file on disk differs from what
              would be generated, or when a role file has a problem

With `--workspace`, custom roles under `<workspace>/_custom/agents/` are
included (`origin: custom`); the committed manifest is generated without it.

The output carries no timestamp, so the same role files always give the same
bytes.

Exit codes: 0 ok; 1 a role file has a problem, or `--check` found a
difference; 2 usage error.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from superagent.tools import agent_roles as ar
from superagent.tools.build_skill_manifest import display_path

HEADER = (
    "# [Do not change manually - generated by tools/build_agent_manifest.py]\n"
    "#\n"
    "# The roster of agent roles under `superagent/agents/` (contracts/agents.md).\n"
    "# One row per `<name>.agent.md`, taken from its frontmatter. Regenerate after\n"
    "# any change to a role file:\n"
    "#   uv run python -m superagent.tools.build_agent_manifest\n"
)


def row_for(role: ar.Role, root: Path) -> dict[str, Any]:
    """The manifest row of one role."""
    return {
        "name": role.name,
        "kind": role.kind,
        "origin": role.origin,
        "path": display_path(role.path, root),
        "dev_twin": display_path(role.dev_path, root) if role.dev_path else None,
        "description": role.description,
        "skills": role.skills if isinstance(role.skills, str) else list(role.skills),
        "owns": list(role.owns),
        "authority": role.authority,
        "model_tier": role.model_tier,
        "duties": [{"id": d.id, "skill": d.skill, "tier": d.tier, "schedule": d.schedule,
                    "check": d.check} for d in role.duties],
    }


def render(roles: list[ar.Role], root: Path) -> str:
    """The manifest text for `roles`."""
    payload = {
        "schema_version": 1,
        "role_count": len(roles),
        "roles": [row_for(role, root) for role in roles],
    }
    return HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(prog="build_agent_manifest")
    parser.add_argument("--framework", type=Path, default=ar.FRAMEWORK)
    parser.add_argument("--workspace", type=Path, default=None,
                        help="Optional workspace root, to include _custom/agents/.")
    parser.add_argument("--output", type=Path, default=None,
                        help="Output path; default <framework>/agents/_manifest.yaml.")
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; exit 1 when the manifest is out of date.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv if argv is not None else sys.argv[1:])
    roles, errors = ar.collect(args.framework, args.workspace)
    if errors:
        for line in errors:
            print(f"build_agent_manifest: {line}", file=sys.stderr)
        return 1
    text = render(roles, args.framework.resolve().parent)
    output = args.output or (args.framework / "agents" / "_manifest.yaml")
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else None
        if current != text:
            print(f"{output} is out of date: run "
                  "`uv run python -m superagent.tools.build_agent_manifest`", file=sys.stderr)
            return 1
        print(f"{output} is up to date ({len(roles)} roles)")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    print(f"Wrote {len(roles)} role rows to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
